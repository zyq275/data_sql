"""落库主键的生成规则。

单独成模块是因为 ``message`` 与 ``query_history`` 两张表都要按"发生顺序"读回来，
它们共用同一条"主键必须自带顺序"的约束。把这套规则写在其中一个仓储里、
让另一个去 import，会让"谁定义了顺序"这件事看起来是偶然的。
"""

from __future__ import annotations

import time
import uuid


def new_id() -> str:
    """普通主键：32 位十六进制 UUID，与 ``user.id`` 同一种形态。"""
    return uuid.uuid4().hex


def new_ordered_id() -> str:
    """时间有序的主键：13 位毫秒时间戳 + 16 位随机。

    **为什么 message 与 query_history 需要这个**：这两张表要按"发生顺序"读回来
    （会话历史、历史列表），但它们的时间列是 MySQL 的 ``DATETIME``，
    **精度只到秒**——``default=datetime.now`` 带的那点微秒在入库时就被截掉了。
    于是同一秒内写入的两条记录 ``created_at`` 完全相同，按它排序得到的次序是
    数据库说不上来的（实践中多半是主键顺序，但没有任何保证）。

    后果不是"排序不好看"：多轮历史一旦错序，就会出现"把上一轮的问题配到这一轮的
    SQL 上"，而 resolve_reference 拿到错乱的上文会改写出一个看似合理、实则跑偏的问题。

    **它保证什么，不保证什么**（这两句的区分很重要）：

    - 跨毫秒严格按时间先后；
    - 同一毫秒内的多次生成**次序稳定**（按随机后缀排，固定不变），但不必是真实先后。
      稳定就够用：分页时同一条记录不会一会儿在第一页、一会儿在第二页。
      而"同一毫秒内发生的两次写"要分出真实先后，本来也没有意义——
      一条会话消息、一条查询历史都各由一次独立的请求写出，同毫秒的概率极低，
      真撞上了它俩之间也没有先后之分可言。

    随机后缀还保证同一毫秒内并发写入不会撞主键；13 位毫秒 + 16 位十六进制的总长
    是 29，远小于 ``VARCHAR(64)``。
    """
    return f"{int(time.time() * 1000):013d}{uuid.uuid4().hex[:16]}"
